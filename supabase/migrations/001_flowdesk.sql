create table if not exists public.flowdesk_accounts (
 id text primary key,email text not null unique,name text not null,password_hash text not null,
 created_at bigint not null,role text not null default 'employee' check(role in ('admin','it','employee')),
 active integer not null default 1 check(active in(0,1)),version integer not null default 0,
 legacy_migrated integer not null default 0
);
create table if not exists public.flowdesk_account_sessions (
 token_hash text primary key,account_id text not null references public.flowdesk_accounts(id),
 expires_at bigint not null,created_at bigint not null
);
create table if not exists public.flowdesk_auth_rate_limits (key text primary key,attempts integer not null,expires_at bigint not null);
create table if not exists public.flowdesk_helpdesk_workspaces (owner_id text primary key,payload text not null,revision integer not null default 0,updated_at text not null);
create table if not exists public.flowdesk_it_tickets (
 id bigint generated by default as identity primary key,requester_id text not null references public.flowdesk_accounts(id),
 assignee_id text references public.flowdesk_accounts(id),body text not null,revision integer not null default 1,
 created_at bigint not null,updated_at bigint not null,legacy_key text unique
);
create index if not exists flowdesk_requester_idx on public.flowdesk_it_tickets(requester_id);
create index if not exists flowdesk_assignee_idx on public.flowdesk_it_tickets(assignee_id);
create index if not exists flowdesk_session_account_idx on public.flowdesk_account_sessions(account_id);
create table if not exists public.flowdesk_role_audit (id text primary key,actor_id text not null,target_id text not null,detail text not null,created_at bigint not null);

alter table public.flowdesk_accounts enable row level security;
alter table public.flowdesk_account_sessions enable row level security;
alter table public.flowdesk_auth_rate_limits enable row level security;
alter table public.flowdesk_helpdesk_workspaces enable row level security;
alter table public.flowdesk_it_tickets enable row level security;
alter table public.flowdesk_role_audit enable row level security;
revoke all on public.flowdesk_accounts,public.flowdesk_account_sessions,public.flowdesk_auth_rate_limits,public.flowdesk_helpdesk_workspaces,public.flowdesk_it_tickets,public.flowdesk_role_audit from public,anon,authenticated;
grant select,insert,update,delete on public.flowdesk_accounts,public.flowdesk_account_sessions,public.flowdesk_auth_rate_limits,public.flowdesk_helpdesk_workspaces,public.flowdesk_it_tickets,public.flowdesk_role_audit to service_role;
revoke all on sequence public.flowdesk_it_tickets_id_seq from public,anon,authenticated;
grant usage,select on sequence public.flowdesk_it_tickets_id_seq to service_role;

create or replace function public.flowdesk_increment_limit(p_key text,p_expires bigint)
returns integer language plpgsql security invoker set search_path = '' as $$
declare result integer;
begin
 insert into public.flowdesk_auth_rate_limits(key,attempts,expires_at) values(p_key,1,p_expires)
 on conflict(key) do update set attempts=public.flowdesk_auth_rate_limits.attempts+1
 returning attempts into result;
 return result;
end;$$;

create or replace function public.flowdesk_change_account(p_input jsonb)
returns boolean language plpgsql security invoker set search_path = '' as $$
declare changed text;
begin
 if p_input->>'role' not in ('admin','it','employee') or (p_input->>'active')::integer not in (0,1) then return false; end if;
 update public.flowdesk_accounts set role=p_input->>'role',active=(p_input->>'active')::integer,version=version+1
 where id=p_input->>'target' and version=(p_input->>'version')::integer
 and id<>p_input->>'actor' and id<>p_input->>'root'
 and exists(select 1 from public.flowdesk_accounts a where a.id=p_input->>'actor' and a.role='admin' and a.active=1)
 returning id into changed;
 if changed is null then return false; end if;
 insert into public.flowdesk_role_audit(id,actor_id,target_id,detail,created_at)
 values(p_input->>'auditId',p_input->>'actor',changed,p_input->>'detail',(p_input->>'now')::bigint);
 delete from public.flowdesk_account_sessions where account_id=changed;
 return true;
end;$$;
revoke all on function public.flowdesk_increment_limit(text,bigint) from public,anon,authenticated;
revoke all on function public.flowdesk_change_account(jsonb) from public,anon,authenticated;
grant execute on function public.flowdesk_increment_limit(text,bigint) to service_role;
grant execute on function public.flowdesk_change_account(jsonb) to service_role;
